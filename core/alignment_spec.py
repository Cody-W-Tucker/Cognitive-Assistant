#!/usr/bin/env python3
"""Generate a personalized alignment verification spec from unified skills.

Reads skills from the unified `workspaces/skills` store and combines them with
the alignment seed template to produce a single alignment spec that downstream
tools can use to evaluate any output.

The orchestrator translation layer (`SOUL.md` and `INTERACTION_POSTURE.md`,
generated by `build-translation-layer`) is retained alongside the spec but is
not an input here; skills are the personalization source.

Skills provide reusable operating procedures generated per profile. They feed
the alignment spec.

"""

from __future__ import annotations

from pathlib import Path
from typing import List, Optional

from core import llm, paths
from core.skill_engine import extract_frontmatter_value, iter_skills

MIN_SPEC_CHARS = 200

SPEC_PREAMBLE = """\
# Personalized Artifact Verification Spec

You are an artifact verifier. You receive an AI-generated artifact (a spec, plan, document, code change, copy, summary, or other deliverable) and assess whether it is production-ready against the personalized checklist below. Run the artifact through each checklist item, score each item, and return a structured verdict.

"""

SPEC_POSTAMBLE = """\

## Instructions

1. Read the artifact in full before scoring. Note its stated purpose, consumer, and form.

2. Run the artifact through each checklist item above. For each item, score:
   - PASS - the artifact satisfies the item's "Satisfied when" cues
   - WEAK - partially satisfied; correctable without rework
   - FAIL - the artifact triggers the item's "Failed when" cues, or omits what the item requires

3. Return the verdict in the format below.

## Output format

```
VERDICT: SHIP | TIGHTEN | REWORK

| # | Checklist Item | Score | Evidence | Fix |
|---|----------------|-------|----------|-----|
| 1 | [item name] | PASS/WEAK/FAIL | [what in the artifact triggered this score] | [one-line correction or -] |

CORRECTIONS (if TIGHTEN):
- [imperative instruction the generating agent can execute]

REWORK (if REWORK):
- [structural problem with the artifact]
- [what the artifact should do instead]
```

Verdict logic:
- SHIP: all PASS, or at most one minor WEAK requiring no correction.
- TIGHTEN: one or more WEAK with actionable corrections; no FAIL.
- REWORK: any FAIL, or compounding WEAK indicating the artifact does not hold together.
"""


def requirements() -> List[str]:
    issues = llm.missing_config(llm.DEFAULT_PROVIDER)
    if not iter_skills():
        issues.append(f"No skills found in {paths.SKILLS_DIR}. Run build-skills or import skills first.")
    return issues


def skills_document() -> str:
    """Every skill in the store, tagged with the group it lives in."""
    blocks = []
    for path in iter_skills():
        content = path.read_text(encoding="utf-8").strip()
        group = path.parent.parent.name
        profile = extract_frontmatter_value(content, "source_profile")
        origin = f' source_profile="{profile}"' if profile else ""
        blocks.append(f'<skill group="{group}"{origin} name="{path.parent.name}">\n{content}\n</skill>')
    print(f"Info: Loaded {len(blocks)} skills")
    return "\n\n".join(blocks)


async def build(*, output_path: Optional[Path] = None) -> Path:
    seed = (paths.ALIGNMENT_PROMPTS_DIR / "seed.md").read_text(encoding="utf-8")
    reply = await llm.complete(
        seed.format(skills_content=skills_document()), min_chars=MIN_SPEC_CHARS, label="alignment spec"
    )
    output = output_path or paths.ALIGNMENT_SPEC_PATH
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(SPEC_PREAMBLE + reply + SPEC_POSTAMBLE + "\n", encoding="utf-8")
    print(f"Info: Wrote alignment spec to {output}")
    return output
